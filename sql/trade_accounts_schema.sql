CREATE TABLE IF NOT EXISTS accounts (
    account_id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    account_name VARCHAR(64) NOT NULL DEFAULT '',
    initial_budget_cent BIGINT UNSIGNED NOT NULL DEFAULT 0,
    available_cent BIGINT UNSIGNED NOT NULL DEFAULT 0,
    frozen_cent BIGINT UNSIGNED NOT NULL DEFAULT 0,
    spent_cent BIGINT UNSIGNED NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
        ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (account_id)
) ENGINE=InnoDB
    DEFAULT CHARSET=utf8mb4
    COLLATE=utf8mb4_0900_ai_ci;